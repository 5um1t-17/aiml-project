DATABASE_ERRORS=(sqlite3.Error,psycopg.Error)
REVIEWER_ROLES=('Credit Manager','Credit Committee')

SCHEMA = """
CREATE TABLE IF NOT EXISTS applications (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    created_at TEXT NOT NULL,
    applicant_income REAL,
    coapplicant_income REAL,
    loan_amount REAL,
    loan_term REAL,
    credit_history INTEGER CHECK (credit_history IN (0, 1)),
    dependents TEXT,
    education TEXT,
    self_employed TEXT,
    property_area TEXT,
    selected_model TEXT NOT NULL,
    model_version TEXT NOT NULL DEFAULT 'legacy',
    is_demo INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
    demo_label TEXT NOT NULL DEFAULT '',
    input_schema TEXT NOT NULL DEFAULT 'legacy-v1',
    input_json TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS predictions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    application_id INTEGER NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    model_name TEXT NOT NULL,
    approved INTEGER NOT NULL CHECK (approved IN (0, 1)),
    probability REAL NOT NULL CHECK (probability BETWEEN 0 AND 1),
    UNIQUE(application_id, model_name)
);
CREATE TABLE IF NOT EXISTS staff_reviews (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    application_id INTEGER NOT NULL REFERENCES applications(id),
    reviewer_name TEXT NOT NULL,
    reviewer_role TEXT NOT NULL CHECK (reviewer_role IN ('Credit Manager', 'Credit Committee')),
    decision TEXT NOT NULL CHECK (decision IN ('accepted', 'rejected', 'pending')),
    notes TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS reviews_application ON staff_reviews(application_id, id);
"""

def connect(path):
    if is_postgres(path):
        return PostgresConnection(path,os.environ.get('DATABASE_SCHEMA','public'))
    connection = sqlite3.connect(path, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute('PRAGMA foreign_keys = ON')
    return connection


def begin_write(connection):
    if isinstance(connection,PostgresConnection):
        connection.execute("SELECT pg_advisory_xact_lock(hashtextextended(current_schema() || ':loanlens-write',0))")
    else:connection.execute('BEGIN IMMEDIATE')


def init_postgres(connection):
    begin_write(connection)
    schema=SCHEMA.replace('INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace('application_id INTEGER','application_id BIGINT').replace(' REAL',' DOUBLE PRECISION')
    for statement in schema.split(';'):
        if statement.strip():connection.execute(statement)
    migrate_reviewer_roles(connection)


def migrate_reviewer_roles(connection):
    """Rename legacy review roles without changing decisions, IDs or timestamps.

    The caller owns the transaction. PostgreSQL upgrades are explicit during
    database initialization, rather than DDL on each serverless cold start.
    """
    if isinstance(connection,PostgresConnection):
        checks=list(connection.execute("""SELECT conname,pg_get_constraintdef(oid) AS definition
            FROM pg_constraint WHERE conrelid='staff_reviews'::regclass AND contype='c'"""))
        legacy=[row for row in checks if 'reviewer_role' in row['definition'] and "'Employee'" in row['definition']]
        if not legacy:return False
        connection.execute('LOCK TABLE staff_reviews IN ACCESS EXCLUSIVE MODE')
        for row in legacy:
            connection.execute(sql.SQL('ALTER TABLE staff_reviews DROP CONSTRAINT {}').format(sql.Identifier(row['conname'])))
    else:
        definition=connection.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name='staff_reviews'").fetchone()
        if not definition or "'Employee'" not in definition[0]:return False
        sequence=connection.execute("SELECT seq FROM sqlite_sequence WHERE name='staff_reviews'").fetchone()
        connection.execute('ALTER TABLE staff_reviews RENAME TO staff_reviews_legacy_roles')
        start=SCHEMA.index('CREATE TABLE IF NOT EXISTS staff_reviews')
        statement=SCHEMA[start:SCHEMA.index('CREATE INDEX',start)].strip().rstrip(';')
        connection.execute(statement)
        connection.execute("""INSERT INTO staff_reviews
            SELECT id,application_id,reviewer_name,CASE reviewer_role
                WHEN 'Employee' THEN 'Credit Manager' WHEN 'Manager' THEN 'Credit Committee' ELSE reviewer_role END,
                decision,notes,created_at FROM staff_reviews_legacy_roles""")
    _rename_review_role_values(connection)
    if isinstance(connection,PostgresConnection):
        connection.execute("ALTER TABLE staff_reviews ADD CONSTRAINT staff_reviews_reviewer_role_check CHECK (reviewer_role IN ('Credit Manager','Credit Committee'))")
    else:
        connection.execute('DROP TABLE staff_reviews_legacy_roles')
        connection.execute('CREATE INDEX IF NOT EXISTS reviews_application ON staff_reviews(application_id,id)')
        if sequence:connection.execute("UPDATE sqlite_sequence SET seq=MAX(seq,?) WHERE name='staff_reviews'",(sequence[0],))
        if connection.execute('PRAGMA foreign_key_check').fetchall():raise sqlite3.IntegrityError('Foreign keys failed after reviewer role migration.')
    return True


def _rename_review_role_values(connection):
    connection.execute("""UPDATE staff_reviews SET reviewer_role=CASE reviewer_role
        WHEN 'Employee' THEN 'Credit Manager' WHEN 'Manager' THEN 'Credit Committee' ELSE reviewer_role END""")
    connection.execute("""UPDATE staff_reviews SET reviewer_name=CASE reviewer_name
        WHEN 'Demo Employee' THEN 'Demo Credit Manager' WHEN 'Demo Manager' THEN 'Demo Credit Committee' ELSE reviewer_name END,
        notes=REPLACE(REPLACE(notes,'fictional employee','fictional credit manager'),'fictional manager','fictional credit committee')
        WHERE application_id IN (SELECT id FROM applications WHERE is_demo=1) AND notes LIKE 'SIMULATED DEMO REVIEW:%'""")

def init_database(path):
    if is_postgres(path):
        with closing(connect(path)) as connection,connection:init_postgres(connection)
        return
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with closing(connect(path)) as connection:
        connection.executescript(SCHEMA)
        info = list(connection.execute('PRAGMA table_info(applications)'))
        if any(row['name'] == 'credit_history' and row['notnull'] for row in info):
            # Legacy required fields have no equivalents in the new source. Keep
            # old rows intact and allow honest NULLs for uncollected new inputs.
            backup_dir = Path(path).parent/'backups'
            backup_dir.mkdir(exist_ok=True)
            backup = backup_dir/('before-kaggle-schema-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')+'.db')
            with closing(sqlite3.connect(backup)) as destination:
                connection.backup(destination)
            definition = SCHEMA.split('CREATE TABLE IF NOT EXISTS predictions')[0]
            connection.execute('PRAGMA foreign_keys = OFF')
            try:
                connection.execute('BEGIN IMMEDIATE')
                connection.execute(definition.replace('CREATE TABLE IF NOT EXISTS applications','CREATE TABLE applications_new',1))
                new_columns = {row['name'] for row in connection.execute('PRAGMA table_info(applications_new)')}
                columns = ','.join('"'+row['name']+'"' for row in info if row['name'] in new_columns)
                previous_sequence = connection.execute("SELECT seq FROM sqlite_sequence WHERE name='applications'").fetchone()
                connection.execute(f'INSERT INTO applications_new ({columns}) SELECT {columns} FROM applications')
                connection.execute('DROP TABLE applications')
                connection.execute('ALTER TABLE applications_new RENAME TO applications')
                if previous_sequence:
                    connection.execute("UPDATE sqlite_sequence SET seq=MAX(seq,?) WHERE name='applications'",(previous_sequence[0],))
                if connection.execute('PRAGMA foreign_key_check').fetchall():
                    raise sqlite3.IntegrityError('Foreign keys failed after schema migration.')
                connection.commit()
            except Exception:
                connection.rollback()
                raise
            finally:
                connection.execute('PRAGMA foreign_keys = ON')
        else:
            columns = {row['name'] for row in info}
            additions = {'model_version':"TEXT NOT NULL DEFAULT 'legacy'",'is_demo':'INTEGER NOT NULL DEFAULT 0',
                'demo_label':"TEXT NOT NULL DEFAULT ''",'input_schema':"TEXT NOT NULL DEFAULT 'legacy-v1'",'input_json':"TEXT NOT NULL DEFAULT ''"}
            for name, definition in additions.items():
                if name not in columns:connection.execute(f'ALTER TABLE applications ADD COLUMN {name} {definition}')
            connection.commit()

        with connection:
            begin_write(connection)
            migrate_reviewer_roles(connection)

def insert_application(connection, data, predictions, selected_model, model_version='legacy', demo_label=''):
    """Keep source-native JSON inputs; legacy columns are display projections only."""
    if 'person_income' in data:
        from personal_loans import SCHEMA as PERSONAL_SCHEMA
        schema,payload=PERSONAL_SCHEMA,json.dumps(data,sort_keys=True)
        projected=(data['person_income']/12,None,data['loan_amnt']/1000,data['loan_term']*12,None,None,None,None,None)
    elif 'income_annum' in data:
        from loan_schema import SCHEMA_ID
        schema, payload = SCHEMA_ID, json.dumps(data,sort_keys=True)
        projected = (data['income_annum']/12, None, data['loan_amount']/1000, data['loan_term']*12,
            None, str(data['no_of_dependents']), data['education'], data['self_employed'], None)
    else:
        schema, payload = 'legacy-v1', ''
        projected = tuple(data[key] for key in ['ApplicantIncome','CoapplicantIncome','LoanAmount','Loan_Amount_Term','Credit_History','Dependents','Education','Self_Employed','Property_Area'])
    query='''INSERT INTO applications (
        created_at, applicant_income, coapplicant_income, loan_amount, loan_term,
        credit_history, dependents, education, self_employed, property_area,
        selected_model, model_version, is_demo, demo_label, input_schema, input_json
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)'''
    if isinstance(connection,PostgresConnection):query+=' RETURNING id'
    cursor = connection.execute(query,
        (datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC'), *projected,
         selected_model, model_version, int(bool(demo_label)), demo_label, schema, payload))
    application_id = cursor.fetchone()['id'] if isinstance(connection,PostgresConnection) else cursor.lastrowid
    connection.executemany('''INSERT INTO predictions (application_id, model_name, approved, probability)
        VALUES (?, ?, ?, ?)''', [(application_id, item['name'], int(item['approved']), item['probability']) for item in predictions])
    return application_id

def save_application(path, data, predictions, selected_model, model_version='legacy'):
    """Commit one application and all results together, or roll back everything."""
    with closing(connect(path)) as connection, connection:
        return insert_application(connection, data, predictions, selected_model, model_version)

def get_history(path, page=1, per_page=20):
    with closing(connect(path)) as connection, connection:
        total = connection.execute('SELECT COUNT(*) FROM applications').fetchone()[0]
        pages = max(1, (total + per_page - 1) // per_page)
        page = max(1, min(page, pages))
        records = [dict(row) for row in connection.execute(
            'SELECT * FROM applications ORDER BY id DESC LIMIT ? OFFSET ?',
            (per_page, (page - 1) * per_page))]
        for record in records:
            record['predictions'] = [dict(row) for row in connection.execute(
                'SELECT model_name, approved, probability FROM predictions WHERE application_id = ? ORDER BY id',
                (record['id'],))]
        return dict(records=records, total=total, page=page, pages=pages)

def save_batch(path, entries, selected_model, model_version='legacy'):
    """Save all validated CSV rows together, or roll back the entire batch."""
    ids = []
    with closing(connect(path)) as connection, connection:
        for data, predictions in entries:
            ids.append(insert_application(connection, data, predictions, selected_model, model_version))
    return ids

def query_applications(path, page=1, search='', status='', per_page=20):
    where, params = [], []
    if search:
        where.append('(CAST(a.id AS TEXT) = ? OR LOWER(a.property_area) LIKE LOWER(?) OR LOWER(a.education) LIKE LOWER(?) OR LOWER(a.demo_label) LIKE LOWER(?))')
        params += [search, '%' + search + '%', '%' + search + '%', '%' + search + '%']
    if status in ('approved', 'declined'):
        where.append('(m.average_probability >= 0.5) = ?')
        params.append(status == 'approved')
    elif status in ('pending', 'accepted', 'rejected'):
        where.append("COALESCE(r.decision, 'pending') = ?")
        params.append(status)
    query = '''FROM applications a LEFT JOIN (
        SELECT application_id, AVG(probability) AS average_probability,
        COUNT(*) AS model_count FROM predictions GROUP BY application_id
        ) m ON m.application_id = a.id
        LEFT JOIN staff_reviews r ON r.id = (
            SELECT MAX(id) FROM staff_reviews WHERE application_id = a.id)'''
    if where:
        query += ' WHERE ' + ' AND '.join(where)
    with closing(connect(path)) as connection:
        total = connection.execute('SELECT COUNT(*) ' + query, params).fetchone()[0]
        pages = max(1, (total + per_page - 1) // per_page)
        page = min(max(1, page), pages)
        records = [dict(row) for row in connection.execute(
            '''SELECT a.*, m.average_probability, m.model_count,
            m.average_probability AS probability, (m.average_probability >= 0.5) AS approved,
            COALESCE(r.decision, 'pending') AS review_status, r.reviewer_name, r.reviewer_role,
            r.notes AS review_notes, r.created_at AS reviewed_at ''' + query + ' ORDER BY a.id DESC LIMIT ? OFFSET ?',
            params + [per_page, (page - 1) * per_page])]
        return dict(records=records, total=total, pages=pages, page=page)

def get_application(path, application_id):
    with closing(connect(path)) as connection:
        row = connection.execute('SELECT * FROM applications WHERE id = ?', (application_id,)).fetchone()
        if row is None:
            return None
        item = dict(row)
        item['predictions'] = [dict(row) for row in connection.execute(
            'SELECT model_name, approved, probability FROM predictions WHERE application_id = ? ORDER BY id', (application_id,))]
        item['reviews'] = [dict(row) for row in connection.execute(
            'SELECT * FROM staff_reviews WHERE application_id = ? ORDER BY id DESC', (application_id,))]
        item['review_status'] = item['reviews'][0]['decision'] if item['reviews'] else 'pending'
        return item

def record_review(path, application_id, reviewer_name, reviewer_role, decision, notes, expected_review_id):
    """Append a staff-entered decision; never derive it from a model score."""
    if reviewer_role not in REVIEWER_ROLES:
        raise ValueError('Choose Credit Manager or Credit Committee as the reviewer role.')
    with closing(connect(path)) as connection, connection:
        begin_write(connection)
        if not connection.execute('SELECT 1 FROM applications WHERE id = ?', (application_id,)).fetchone():
            raise LookupError('Application not found.')
        latest = connection.execute('SELECT COALESCE(MAX(id), 0) FROM staff_reviews WHERE application_id = ?', (application_id,)).fetchone()[0]
        if latest != expected_review_id:
            raise ValueError('Another review was saved while this page was open. Read the latest review and try again.')
        query='''INSERT INTO staff_reviews
            (application_id, reviewer_name, reviewer_role, decision, notes, created_at)
            VALUES (?, ?, ?, ?, ?, ?)'''
        if isinstance(connection,PostgresConnection):query+=' RETURNING id'
        cursor = connection.execute(query, (application_id, reviewer_name, reviewer_role, decision, notes,
                datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')))
        return cursor.fetchone()['id'] if isinstance(connection,PostgresConnection) else cursor.lastrowid

def dashboard_stats(path):
    with closing(connect(path)) as connection:
        stats = dict(connection.execute('''SELECT COUNT(*) AS total,
            COALESCE(SUM(CASE WHEN m.score >= 0.5 THEN 1 ELSE 0 END), 0) AS approved,
            COALESCE(AVG(m.score), 0) AS avg_score,
            COALESCE(SUM(a.loan_amount), 0) AS amount,
            COALESCE(SUM(CASE WHEN COALESCE(r.decision, 'pending') = 'pending' THEN 1 ELSE 0 END), 0) AS pending,
            COALESCE(SUM(CASE WHEN r.decision = 'accepted' THEN 1 ELSE 0 END), 0) AS accepted,
            COALESCE(SUM(CASE WHEN r.decision = 'rejected' THEN 1 ELSE 0 END), 0) AS rejected
            FROM applications a LEFT JOIN (
                SELECT application_id, AVG(probability) AS score FROM predictions GROUP BY application_id
            ) m ON m.application_id = a.id
            LEFT JOIN staff_reviews r ON r.id = (
                SELECT MAX(id) FROM staff_reviews WHERE application_id = a.id)''').fetchone())
        stats['declined'] = stats['total'] - stats['approved']
        stats['approval_rate'] = stats['approved'] / stats['total'] if stats['total'] else 0
        stats['trend'] = [dict(row) for row in connection.execute('''SELECT SUBSTR(created_at, 1, 10) AS day,
            COUNT(*) AS count FROM applications GROUP BY day ORDER BY day DESC LIMIT 7''')][::-1]
        stats['disagreement'] = connection.execute('''SELECT COUNT(*) FROM (
            SELECT application_id FROM predictions GROUP BY application_id
            HAVING MIN(approved) != MAX(approved)) AS disagreements''').fetchone()[0]
        return stats

def export_records(path, search='', status=''):
    records = query_applications(path, search=search, status=status, per_page=2147483647)['records']
    with closing(connect(path)) as connection:
        for record in records:
            for result in connection.execute('SELECT model_name, approved, probability FROM predictions WHERE application_id = ? ORDER BY id', (record['id'],)):
                yield {**record, **dict(result)}
